// Builds db/seed/golfs.sql from db/seed/golfs.json (+ db/seed/sources.json).
// Idempotent: re-running the SQL upserts golfs by slug and sources by URL.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const golfs = JSON.parse(readFileSync('db/seed/golfs.json', 'utf8'));
const extraSources = existsSync('db/seed/sources.json') ? JSON.parse(readFileSync('db/seed/sources.json', 'utf8')) : [];

const q = (v) => (v === null || v === undefined || v === '' ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
export const slugify = (s) =>
  s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const lines = ['-- Generated by scripts/build-seed.mjs — do not edit by hand.'];
const seen = new Set();
for (const g of golfs) {
  let slug = g.slug ?? slugify(`${g.name}-${g.city}`);
  while (seen.has(slug)) slug += '-2';
  seen.add(slug);
  g.slug = slug;
  lines.push(
    `INSERT INTO golfs (slug, name, department, city, postcode, lat, lng, holes, website, phone, ffgolf_id, notes, email, address, photo_url) VALUES (${[
      slug, g.name, g.department, g.city, g.postcode, g.lat, g.lng, g.holes, g.website, g.phone, g.ffgolf_id, g.notes, g.email, g.address, g.photo_url,
    ].map(q).join(', ')}) ON CONFLICT(slug) DO UPDATE SET name=excluded.name, department=excluded.department, city=excluded.city, postcode=excluded.postcode, lat=excluded.lat, lng=excluded.lng, holes=excluded.holes, website=excluded.website, phone=excluded.phone, ffgolf_id=excluded.ffgolf_id, notes=excluded.notes, email=excluded.email, address=excluded.address, photo_url=excluded.photo_url, updated_at=datetime('now');`,
  );
}

const sourceLines = [];
const pushSource = (golfSlug, kind, parser, label, url) => {
  if (!url || !/^https?:\/\//.test(url)) return;
  const golfRef = golfSlug ? `(SELECT id FROM golfs WHERE slug = ${q(golfSlug)})` : 'NULL';
  sourceLines.push(
    `INSERT INTO sources (golf_id, kind, parser, label, url) VALUES (${golfRef}, ${q(kind)}, ${q(parser)}, ${q(label)}, ${q(url)}) ON CONFLICT(url) DO NOTHING;`,
  );
};
for (const g of golfs) {
  if (g.competitions_url) pushSource(g.slug, 'club_page', /\.ics($|\?)/.test(g.competitions_url) ? 'ical' : 'llm', `${g.name} — calendrier`, g.competitions_url);
}
for (const s of extraSources) {
  const golf = s.golf ? golfs.find((g) => g.slug === s.golf || g.name === s.golf) : null;
  pushSource(golf?.slug ?? null, s.kind ?? 'club_page', s.parser ?? 'llm', s.label, s.url);
}

writeFileSync('db/seed/golfs.sql', [...lines, ...sourceLines].join('\n') + '\n');
console.log(`${golfs.length} golfs, ${sourceLines.length} sources → db/seed/golfs.sql`);
